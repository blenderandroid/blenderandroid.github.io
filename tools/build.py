class Update(object):
    def __init__(self, meta, body, path):
        self.meta = meta
        self.body = body
        self.path = path
        self.slug = meta.get("slug") or self._slug()
        self.title = meta.get("title", "Untitled")
        self.track = meta.get("track", "main")
        self.tag = meta.get("tag", "")
        self.date = self._date()
        self.release_url = meta.get("release_url", "")
        self.summary = meta.get("summary", "")
        self.assets = meta.get("assets") or []
        self.prerelease = meta.get("prerelease", True)

    def _slug(self):
        base = os.path.basename(self.path)
        base = re.sub(r"\.md$", "", base)
        return re.sub(r"[^a-z0-9\-]+", "-", base.lower()).strip("-")

    def _date(self):
        raw = str(self.meta.get("date", ""))[:10]
        try:
            return dt.date(*[int(x) for x in raw.split("-")])
        except Exception:
            return dt.date(1970, 1, 1)

    @property
    def url(self):
        return "/updates/%s/" % self.slug

    def date_label(self):
        return "%d %s %d" % (self.date.day, self.date.strftime("%b"), self.date.year)


def split_frontmatter(text):
    text = text.replace("\r\n", "\n")
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    fm = text[3:end].strip("\n")
    body = text[end + 4:].lstrip("\n")
    meta = parse_yaml(fm) if fm.strip() else {}
    return (meta or {}), body


def load_site():
    path = os.path.join(CONTENT, "site.yaml")
    with open(path, encoding="utf-8") as fh:
        return parse_yaml(fh.read())


def load_updates():
    items = []
    if not os.path.isdir(UPDATES_DIR):
        return items
    for name in sorted(os.listdir(UPDATES_DIR)):
        if not name.endswith(".md"):
            continue
        path = os.path.join(UPDATES_DIR, name)
        with open(path, encoding="utf-8") as fh:
            meta, body = split_frontmatter(fh.read())
        items.append(Update(meta, body, path))
    items.sort(key=lambda u: (u.date, u.slug), reverse=True)
    return items


def kind_label(site, track):
    """Track name for a release, or a kind name for an announcement."""
    t = site.get("tracks", {}).get(track)
    if t:
        return t.get("name", track)
    k = (site.get("kinds") or {}).get(track)
    if k:
        return k.get("name", track)
    return track.replace("-", " ").title()


class Page(object):
    """A standalone page such as About. Same markdown, no release attached."""

    def __init__(self, meta, body, path):
        self.meta = meta
        self.body = body
        self.path = path
        self.slug = meta.get("slug") or re.sub(r"\.md$", "", os.path.basename(path))
        self.title = meta.get("title") or self.slug.replace("-", " ").capitalize()
        self.nav = meta.get("nav", self.title)
        self.order = int(meta.get("order", 100) or 100)
        self.description = meta.get("description", "")
        self.lede = meta.get("lede", "")

    @property
    def url(self):
        return "/%s/" % self.slug


def load_pages():
    items = []
    if not os.path.isdir(PAGES_DIR):
        return items
    for name in sorted(os.listdir(PAGES_DIR)):
        if not name.endswith(".md"):
            continue
        path = os.path.join(PAGES_DIR, name)
        with open(path, encoding="utf-8") as fh:
            meta, body = split_frontmatter(fh.read())
        items.append(Page(meta, body, path))
    items.sort(key=lambda p: (p.order, p.slug))
    return items


def latest_per_track(updates):
    out = {}
    for u in updates:
        if u.track not in out:
            out[u.track] = u
    return out


