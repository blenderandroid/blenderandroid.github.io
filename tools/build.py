# --------------------------------------------------------------------------
# A small YAML subset: nested maps, lists of scalars, lists of maps, scalars.
# Enough for this project's frontmatter and site config, and nothing more.
# --------------------------------------------------------------------------

def _scalar(raw):
    raw = raw.strip()
    if not raw:
        return ""
    if raw[0] in "\"'" and raw[-1] == raw[0] and len(raw) >= 2:
        return raw[1:-1]
    low = raw.lower()
    if low in ("true", "yes"):
        return True
    if low in ("false", "no"):
        return False
    if low in ("null", "~"):
        return None
    if re.fullmatch(r"-?\d+", raw):
        return int(raw)
    if re.fullmatch(r"-?\d+\.\d+", raw):
        return float(raw)
    return raw


def _indent_of(line):
    return len(line) - len(line.lstrip(" "))


def parse_yaml(text):
    """Parse the supported subset into Python objects."""
    lines = []
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        lines.append(raw.rstrip())
    value, _ = _parse_block(lines, 0, _indent_of(lines[0]) if lines else 0)
    return value


def _parse_block(lines, i, indent):
    if i >= len(lines):
        return {}, i
    if lines[i].lstrip().startswith("- "):
        return _parse_list(lines, i, indent)
    return _parse_map(lines, i, indent)


def _parse_map(lines, i, indent):
    out = {}
    while i < len(lines):
        line = lines[i]
        cur = _indent_of(line)
        if cur < indent:
            break
        if cur > indent:
            raise ValueError("unexpected indent at: %s" % line.strip())
        stripped = line.strip()
        if stripped.startswith("- "):
            break
        if ":" not in stripped:
            raise ValueError("expected 'key: value' at: %s" % stripped)
        key, _, rest = stripped.partition(":")
        key = key.strip()
        rest = rest.strip()
        if rest == "|":
            # literal block: keep newlines
            i += 1
            buf = []
            while i < len(lines) and _indent_of(lines[i]) > indent:
                buf.append(lines[i][indent + 2:])
                i += 1
            out[key] = "\n".join(buf)
            continue
        if rest == ">":
            # folded block: join into one line
            i += 1
            buf = []
            while i < len(lines) and _indent_of(lines[i]) > indent:
                buf.append(lines[i].strip())
                i += 1
            out[key] = " ".join(buf)
            continue
        if rest == "":
            nxt = i + 1
            if nxt < len(lines) and _indent_of(lines[nxt]) > indent:
                child, i = _parse_block(lines, nxt, _indent_of(lines[nxt]))
                out[key] = child
                continue
            out[key] = ""
            i += 1
            continue
        out[key] = _scalar(rest)
        i += 1
    return out, i


def _parse_list(lines, i, indent):
    out = []
    while i < len(lines):
        line = lines[i]
        cur = _indent_of(line)
        if cur < indent or not line.strip().startswith("- "):
            break
        body = line.strip()[2:]
        if ":" in body and not body.startswith(("http://", "https://")):
            # a map whose first key shares the dash line
            sub_lines = [" " * (indent + 2) + body]
            i += 1
            while i < len(lines) and _indent_of(lines[i]) > indent:
                sub_lines.append(lines[i])
                i += 1
            item, _ = _parse_map(sub_lines, 0, indent + 2)
            out.append(item)
            continue
        out.append(_scalar(body))
        i += 1
    return out, i


# --------------------------------------------------------------------------
# Markdown. A renderer for the syntax these release notes actually use:
# headings, bold, italic, inline code, links, fenced code, lists, tables,
# blockquotes, GitHub alerts and rules. Not a general CommonMark engine.
# --------------------------------------------------------------------------

INLINE_CODE = re.compile(r"`([^`]+)`")
BOLD = re.compile(r"\*\*(.+?)\*\*", re.S)
ITALIC = re.compile(r"(?<![\*\w])\*([^\*\n]+)\*(?!\*)")
IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+\"([^\"]*)\")?\)")
LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
BARE_URL = re.compile(r"(?<![\"'=(>])\bhttps?://[^\s<>()]+")
ALERT = re.compile(r"^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*$", re.I)
YT_ID = re.compile(r"(?:youtu\.be/|v=|embed/|shorts/)([A-Za-z0-9_-]{6,20})")


def _esc(s):
    return html.escape(s, quote=False)


def inline(text):
    """Render inline markdown. Code spans are protected from other rules."""
    spans = []

    def stash(m):
        spans.append(m.group(1))
        return "\x00%d\x00" % (len(spans) - 1)

    text = INLINE_CODE.sub(stash, text)
    text = _esc(text)
    text = IMAGE.sub(
        lambda m: '<img src="%s" alt="%s" loading="lazy" decoding="async">'
                  % (html.escape(m.group(2), quote=True), html.escape(m.group(1), quote=True)),
        text,
    )
    text = LINK.sub(
        lambda m: '<a href="%s">%s</a>' % (html.escape(m.group(2), quote=True), m.group(1)),
        text,
    )
    text = BARE_URL.sub(lambda m: '<a href="%s">%s</a>' % (m.group(0), m.group(0)), text)
    text = BOLD.sub(lambda m: "<strong>%s</strong>" % m.group(1), text)
    text = ITALIC.sub(lambda m: "<em>%s</em>" % m.group(1), text)
    for idx, code in enumerate(spans):
        text = text.replace("\x00%d\x00" % idx, "<code>%s</code>" % _esc(code))
    return text


def _table(rows):
    head = rows[0]
    body = rows[2:]
    out = ['<div class="tablewrap"><table><thead><tr>']
    for cell in head:
        out.append("<th>%s</th>" % inline(cell))
    out.append("</tr></thead><tbody>")
    for row in body:
        out.append("<tr>")
        for cell in row:
            out.append("<td>%s</td>" % inline(cell))
        out.append("</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)


def _split_row(line):
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def render_markdown(text):
    lines = text.replace("\r\n", "\n").split("\n")
    out = []
    i = 0
    n = len(lines)

    while i < n:
        line = lines[i]
        stripped = line.strip()

        if not stripped:
            i += 1
            continue

        # fenced code
        if stripped.startswith("```"):
            lang = stripped[3:].strip()
            i += 1
            buf = []
            while i < n and not lines[i].strip().startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            if lang.lower() in ("youtube", "video"):
                out.append(youtube_embed("\n".join(buf).strip()))
                continue
            cls = ' class="lang-%s"' % _esc(lang) if lang else ""
            out.append("<pre><code%s>%s</code></pre>" % (cls, _esc("\n".join(buf))))
            continue

        # horizontal rule
        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", stripped):
            out.append("<hr>")
            i += 1
            continue

        # heading
        m = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if m:
            # the page owns h1, so the notes' own headings start one level down
            level = min(len(m.group(1)) + 1, 6)
            out.append("<h%d>%s</h%d>" % (level, inline(m.group(2).strip()), level))
            i += 1
            continue

        # table
        if "|" in stripped and i + 1 < n and re.fullmatch(r"[\s|:\-]+", lines[i + 1].strip()) \
                and "-" in lines[i + 1]:
            rows = []
            while i < n and "|" in lines[i]:
                rows.append(_split_row(lines[i]))
                i += 1
            if len(rows) >= 2:
                out.append(_table(rows))
                continue

        # blockquote, including GitHub alerts
        if stripped.startswith(">"):
            buf = []
            while i < n and lines[i].strip().startswith(">"):
                buf.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            kind = ""
            if buf:
                am = ALERT.match(buf[0].strip())
                if am:
                    kind = am.group(1).lower()
                    buf = buf[1:]
            cls = "quote alert alert--%s" % kind if kind else "quote"
            inner = render_markdown("\n".join(buf))
            label = ('<p class="alert-label">%s</p>' % kind.upper()) if kind else ""
            out.append('<blockquote class="%s">%s%s</blockquote>' % (cls, label, inner))
            continue

        # lists
        lm = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", line)
        if lm:
            block, i = _list(lines, i, _indent_of(line))
            out.append(block)
            continue

        # paragraph
        buf = []
        while i < n and lines[i].strip() and not re.match(
                r"^\s*(#{1,6}\s|>|```|[-*+]\s|\d+\.\s)", lines[i]) \
                and not re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", lines[i].strip()):
            buf.append(lines[i].strip())
            i += 1
        if buf:
            joined = " ".join(buf)
            solo = IMAGE.fullmatch(joined.strip())
            if solo:
                out.append(figure(solo.group(2), solo.group(1), solo.group(3)))
            else:
                out.append("<p>%s</p>" % inline(joined))
        else:
            i += 1

    return "\n".join(out)


def figure(src, alt, caption=None):
    cap = ""
    if caption:
        cap = "<figcaption>%s</figcaption>" % inline(caption)
    elif alt:
        cap = "<figcaption>%s</figcaption>" % inline(alt)
    return ('<figure class="fig"><img src="%s" alt="%s" loading="lazy" '
            'decoding="async">%s</figure>'
            % (html.escape(src, quote=True), html.escape(alt or "", quote=True), cap))


def youtube_embed(raw):
    """A plain lazy iframe: it needs no JavaScript and sets no cookie until played."""
    raw = raw.strip()
    m = YT_ID.search(raw)
    vid = m.group(1) if m else re.sub(r"[^A-Za-z0-9_-]", "", raw)
    if not vid:
        return ""
    return ('<div class="embed embed--video">'
            '<iframe src="https://www.youtube-nocookie.com/embed/%s" '
            'title="Video" loading="lazy" allowfullscreen '
            'allow="accelerometer; encrypted-media; gyroscope; picture-in-picture" '
            'referrerpolicy="strict-origin-when-cross-origin"></iframe></div>' % vid)


def _list(lines, i, indent):
    n = len(lines)
    first = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", lines[i])
    ordered = bool(re.fullmatch(r"\d+\.", first.group(2)))
    items = []
    while i < n:
        line = lines[i]
        if not line.strip():
            # a blank line only ends the list if the next content dedents out
            j = i + 1
            while j < n and not lines[j].strip():
                j += 1
            if j >= n or _indent_of(lines[j]) < indent or not re.match(
                    r"^\s*([-*+]|\d+\.)\s+", lines[j]):
                break
            i = j
            continue
        cur = _indent_of(line)
        if cur < indent:
            break
        m = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", line)
        if not m or cur > indent:
            break
        buf = [m.group(3)]
        i += 1
        # continuation lines and nested lists belong to this item
        while i < n:
            if not lines[i].strip():
                nxt = i + 1
                while nxt < n and not lines[nxt].strip():
                    nxt += 1
                if nxt < n and _indent_of(lines[nxt]) > indent:
                    buf.append("")
                    i = nxt
                    continue
                break
            if _indent_of(lines[i]) > indent:
                buf.append(lines[i][indent:])
                i += 1
                continue
            break
        inner = "\n".join(buf)
        if re.search(r"^\s*([-*+]|\d+\.)\s+", inner, re.M) and "\n" in inner:
            items.append(render_markdown(inner))
        else:
            items.append(inline(" ".join(x.strip() for x in inner.split("\n") if x.strip())))
    tag = "ol" if ordered else "ul"
    body = "".join("<li>%s</li>" % it for it in items)
    return "<%s>%s</%s>" % (tag, body, tag), i


