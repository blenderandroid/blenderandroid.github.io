def strip_leading_title(body, title):
    """Drop the notes' own opening heading when the page header already says it."""
    lines = body.lstrip().split("\n")
    if not lines:
        return body
    m = re.match(r"^#{1,2}\s+(.*)$", lines[0].strip())
    if not m:
        return body
    def norm(s):
        return re.sub(r"[^a-z0-9]+", "", s.lower())
    head, want = norm(m.group(1)), norm(title)
    if head and (head in want or want in head):
        return "\n".join(lines[1:]).lstrip("\n")
    return body


def normalize_headings(md):
    """Shift headings so the document's own top level lands on h2.

    Authors write `#` or `##` for their first section depending on habit, and
    the page already owns the h1. Rebasing here means either habit produces a
    correct outline instead of jumping h1 to h3.
    """
    lines = (md or "").replace("\r\n", "\n").split("\n")
    levels, fenced = [], False
    for ln in lines:
        if ln.strip().startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = re.match(r"^(#{1,6})\s+\S", ln.strip())
        if m:
            levels.append(len(m.group(1)))
    if not levels:
        return md

    shift = 1 - min(levels)
    if shift == 0:
        return md

    out, fenced = [], False
    for ln in lines:
        if ln.strip().startswith("```"):
            fenced = not fenced
            out.append(ln)
            continue
        m = re.match(r"^(#{1,6})(\s+\S.*)$", ln.strip()) if not fenced else None
        if m:
            lvl = max(1, min(6, len(m.group(1)) + shift))
            out.append("#" * lvl + m.group(2))
        else:
            out.append(ln)
    return "\n".join(out)


