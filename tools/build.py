GH_TAG = re.compile(r"github\.com/([^/]+)/([^/]+)/releases/tag/([^/?#]+)")
GH_REPO = re.compile(r"github\.com/([^/]+)/([^/]+)/?$")
SHA_LINE = re.compile(r"\b([0-9a-f]{64})\b")


def fetch_json(url):
    req = urllib.request.Request(url, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "blenderandroid-site-build",
    })
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", "Bearer %s" % token)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        sys.exit("GitHub returned %s for %s\n%s" % (exc.code, url, exc.read()[:400]))
    except urllib.error.URLError as exc:
        sys.exit("could not reach GitHub: %s" % exc.reason)


def label_for(name):
    low = name.lower()
    if "lite" in low:
        return "Lite"
    if "full" in low:
        return "Full"
    return "APK"


def find_sha(body, asset_name):
    """Best effort, most reliable evidence first. Never guesses between candidates."""
    if not body:
        return ""

    # 1. sha256sum output: "<hash>  <filename>", either order
    for pat in (r"\b([0-9a-f]{64})\b[ \t]+\*?%s\b",
                r"\b%s\b[ \t:]+([0-9a-f]{64})\b"):
        m = re.search(pat % re.escape(asset_name), body, re.I)
        if m:
            return m.group(1).lower()

    # 2. a hash within the same block as the filename
    idx = body.find(asset_name)
    if idx != -1:
        window = body[max(0, idx - 400): idx + 400]
        m = SHA_LINE.search(window)
        if m:
            return m.group(1)

    # 3. exactly one hash in the whole body that is not the signing fingerprint
    found = [h for h in set(SHA_LINE.findall(body))
             if not re.search(r"SHA-256:\s*" + h, body)]
    if len(found) == 1:
        return found[0]
    return ""


def cmd_import(args):
    site = load_site()
    url = args.url
    m = GH_TAG.search(url)
    if m:
        owner, repo, tag = m.group(1), m.group(2), m.group(3)
        api = "https://api.github.com/repos/%s/%s/releases/tags/%s" % (owner, repo, tag)
    else:
        m = GH_REPO.search(url.rstrip("/"))
        if not m:
            sys.exit("expected a release URL or a repo URL, got: %s" % url)
        owner, repo = m.group(1), m.group(2)
        api = "https://api.github.com/repos/%s/%s/releases/latest" % (owner, repo)

    print("fetching %s" % api)
    data = fetch_json(api)

    full_name = "%s/%s" % (owner, repo)
    track = args.track
    if not track:
        for tid, t in site.get("tracks", {}).items():
            if t.get("repo", "").lower() == full_name.lower():
                track = tid
                break
    if not track:
        sys.exit("could not match %s to a track in content/site.yaml; pass --track"
                 % full_name)

    body = data.get("body") or ""
    assets = []
    for a in data.get("assets", []):
        assets.append({
            "name": a["name"],
            "label": label_for(a["name"]),
            "bytes": a["size"],
            "url": a["browser_download_url"],
            "sha256": find_sha(body, a["name"]),
            "downloads": a.get("download_count", 0),
        })

    date = (data.get("published_at") or "")[:10] or dt.date.today().isoformat()
    tag = data.get("tag_name", "")
    slug = slug_for(date, track, tag)
    path = os.path.join(UPDATES_DIR, slug + ".md")
    if os.path.exists(path) and not args.force:
        sys.exit("%s already exists (use --force to overwrite)" % path)

    title = args.title or data.get("name") or tag
    # the first real sentence of the notes makes a serviceable first summary
    summary = ""
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith(("#", ">", "-", "*", "|", "`")):
            summary = re.sub(r"\*\*|`", "", line)
            break

    text = TEMPLATE % {
        "title": title,
        "track": track,
        "tag": tag,
        "date": date,
        "release_url": data.get("html_url", ""),
        "summary": summary or "Edit this summary; it is what the feed shows.",
        "assets": asset_block(assets),
        "body": body.strip() + "\n",
    }
    write(path, text)
    missing = [a["name"] for a in assets if not a["sha256"]]
    if missing:
        print("\n  note: no SHA-256 found in the notes for: %s" % ", ".join(missing))
        print("  the page will say so rather than invent one.")
    print("\nReview and hand-tune that file, then run: python tools/build.py")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")

    sub.add_parser("build", help="regenerate the site (default)")

    p_new = sub.add_parser("new", help="scaffold an update or an announcement")
    p_new.add_argument("--track", default="", help="track id from site.yaml; omit for an announcement")
    p_new.add_argument("--tag", default="", help="release tag")
    p_new.add_argument("--title", default="", help="post title")
    p_new.add_argument("--date", default="", help="YYYY-MM-DD, defaults to today")
    p_new.add_argument("--force", action="store_true")

    p_imp = sub.add_parser("import", help="pull a GitHub release into an update")
    p_imp.add_argument("url", help="release URL, or repo URL for the latest release")
    p_imp.add_argument("--track", default="", help="override the track id")
    p_imp.add_argument("--title", default="", help="override the title")
    p_imp.add_argument("--force", action="store_true")

    args = ap.parse_args()
    if args.cmd == "new":
        cmd_new(args)
    elif args.cmd == "import":
        cmd_import(args)
    else:
        cmd_build(args)


if __name__ == "__main__":
    main()
