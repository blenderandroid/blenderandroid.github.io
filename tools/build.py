def chrome_nav(depth):
    links = ['<a href="%s">Log</a>' % rel(depth, "updates/index.html")]
    for pg in load_pages():
        links.append('<a href="%s">%s</a>'
                     % (rel(depth, pg.slug + "/index.html"), _esc(pg.nav)))
    return "".join(links)


def footer_cols(site, depth):
    out = []
    for track_id, track in site.get("tracks", {}).items():
        out.append(
            '<div class="fcol"><h2>%s</h2><a href="%s">Releases</a><a href="%s">Source</a></div>'
            % (_esc(track["name"]),
               html.escape(track["releases_url"], quote=True),
               html.escape(track["repo_url"], quote=True))
        )
    links = ['<a href="%s">Porting log</a>' % rel(depth, "updates/index.html"),
             '<a href="%s">Downloads</a>' % (rel(depth, "index.html") + "#download")]
    for pg in load_pages():
        links.append('<a href="%s">%s</a>'
                     % (rel(depth, pg.slug + "/index.html"), _esc(pg.nav)))
    out.append('<div class="fcol"><h2>This site</h2>%s</div>' % "".join(links))
    out.append(
        '<div class="fcol"><h2>Blender</h2>'
        '<a href="https://www.blender.org">blender.org</a>'
        '<a href="https://projects.blender.org">Upstream development</a></div>'
    )
    return "".join(out)


