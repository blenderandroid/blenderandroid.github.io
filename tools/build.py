def write(path, text):
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("  wrote %s" % os.path.relpath(path, ROOT).replace("\\", "/"))


def cmd_build(args):
    site = load_site()
    updates = load_updates()
    if not updates:
        print("warning: no updates found in content/updates/")
    latest = latest_per_track(updates)

    print("building %d update(s)" % len(updates))
    write(os.path.join(ROOT, "index.html"), build_home(site, updates, latest))
    write(os.path.join(OUT_UPDATES, "index.html"), build_updates_index(site, updates))

    # remove pages for updates that no longer exist
    keep = {u.slug for u in updates}
    if os.path.isdir(OUT_UPDATES):
        for name in os.listdir(OUT_UPDATES):
            p = os.path.join(OUT_UPDATES, name)
            if os.path.isdir(p) and name not in keep:
                shutil.rmtree(p)
                print("  removed stale %s" % name)

    for i, u in enumerate(updates):
        write(os.path.join(OUT_UPDATES, u.slug, "index.html"),
              build_post(site, u, updates, i))

    pages = load_pages()
    for pg in pages:
        write(os.path.join(ROOT, pg.slug, "index.html"), build_standalone(site, pg))
    prune_stale_pages({p.slug for p in pages})
    print("done")


def prune_stale_pages(keep):
    """Remove page directories whose markdown file is gone.

    Only directories holding an index.html this generator wrote are considered,
    so a hand-made folder in the repository root is never touched.
    """
    for name in os.listdir(ROOT):
        if name in keep or name.startswith(".") or name == "updates":
            continue
        target = os.path.join(ROOT, name)
        index = os.path.join(target, "index.html")
        if not os.path.isdir(target) or not os.path.isfile(index):
            continue
        try:
            with open(index, encoding="utf-8") as fh:
                if GENERATED_NOTE not in fh.read(4096):
                    continue
        except OSError:
            continue
        shutil.rmtree(target)
        print("  removed stale page %s" % name)


