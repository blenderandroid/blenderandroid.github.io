def mib(nbytes):
    try:
        return "%.1f MiB" % (int(nbytes) / 1048576.0)
    except Exception:
        return ""


def mb_short(nbytes):
    try:
        return "%d MB" % round(int(nbytes) / 1048576.0)
    except Exception:
        return ""


def rel(depth, path):
    """Site-root-relative path turned into a document-relative one."""
    path = path.lstrip("/")
    return ("../" * depth) + path if depth else path


